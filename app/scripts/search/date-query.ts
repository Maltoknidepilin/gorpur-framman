/** CQP matches the entire metadata value; suffixes include finer known precision. */
const YEAR_SUFFIX = "(-[0-9]{2}(-[0-9]{2})?)?"
const MONTH_SUFFIX = "(-[0-9]{2})?"

export function dateQuery(value: string): string {
    const match = /^(\d{4})(?:-(\d{2})(?:-(\d{2}))?)?$/.exec(value)
    if (!match) return ""
    const [, year, month, day] = match
    if (Number(year) < 1) return ""
    if (month && (Number(month) < 1 || Number(month) > 12)) return ""
    if (day) {
        const date = new Date(0)
        date.setUTCFullYear(Number(year), Number(month) - 1, Number(day))
        if (date.getUTCMonth() !== Number(month) - 1 || date.getUTCDate() !== Number(day)) return ""
    }
    return value + (day ? "" : month ? MONTH_SUFFIX : YEAR_SUFFIX)
}

/** Restore the readable date from a saved query, including legacy exact dates. */
export function dateQueryValue(query: string): string {
    let value = query
    for (const suffix of [YEAR_SUFFIX, MONTH_SUFFIX]) {
        if (value.endsWith(suffix)) {
            value = value.slice(0, -suffix.length)
            break
        }
    }
    return dateQuery(value) ? value : ""
}

/** Inclusive year bounds using ordinary CQP regexp matching, as dateQuery does. */
export function yearRangeQuery(from = "", to = ""): string {
    const valid = (value: string) => /^\d{4}$/.test(value) && Number(value) >= 1
    if ((!from && !to) || (from && !valid(from)) || (to && !valid(to))) return ""
    const lower = Number(from || "0001")
    const upper = Number(to || "9999")
    if (lower > upper) return ""
    const parts: string[] = []
    // Emit aligned decimal blocks, not an enumeration of every year.
    const visit = (prefix: string) => {
        const remaining = 4 - prefix.length
        const min = Number(prefix.padEnd(4, "0"))
        const max = Number(prefix.padEnd(4, "9"))
        if (max < lower || min > upper) return
        if (min >= lower && max <= upper) {
            parts.push(prefix + (remaining ? `[0-9]${remaining > 1 ? `{${remaining}}` : ""}` : ""))
        } else {
            for (let digit = 0; digit < 10; digit++) visit(prefix + digit)
        }
    }
    visit("")
    return parts.length === 1 ? parts[0] : `(${parts.join("|")})`
}

/** Restore the bounds of expressions generated by yearRangeQuery. */
export function yearRangeQueryValue(query: string): { from: string; to: string } | undefined {
    if (/^\d{4}$/.test(query) && Number(query) >= 1) return { from: query, to: query }
    const parts = query.replace(/^\(|\)$/g, "").split("|")
    const bounds = parts.map((part) => {
        const match = /^(\d*)(?:\[0-9\](?:\{([1-4])\})?)?$/.exec(part)
        if (!match) return undefined
        const [, prefix, count] = match
        const remaining = part.includes("[0-9]") ? Number(count || 1) : 0
        if (prefix.length + remaining !== 4) return undefined
        return [Number(prefix.padEnd(4, "0")), Number(prefix.padEnd(4, "9"))]
    })
    if (bounds.some((bound) => !bound)) return undefined
    const from = String(Math.min(...bounds.map((bound) => bound![0]))).padStart(4, "0")
    const to = String(Math.max(...bounds.map((bound) => bound![1]))).padStart(4, "0")
    if (yearRangeQuery(from, to) !== query) return undefined
    return { from: from === "0001" ? "" : from, to: to === "9999" ? "" : to }
}
